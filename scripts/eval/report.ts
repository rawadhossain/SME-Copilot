// Runs the cases and builds the two result files (JSON and Markdown). Pure aggregation over CaseResult; nothing here reads a clock.
// Output is deterministic for a given seed: no timestamps, no ids, sorted, money as integer-minor-unit strings in the JSON.
import { closeEnv, createEnv, OUTCOMES, runCase, type CaseResult, type OutcomeClass } from "./run-case";
import { describeParams, generateCases, RANGES, type CaseParams } from "./generate";

export const HEADER = "generated by bun run eval; deterministic for a given seed; synthetic companies and simulated counterparties; measures the pipeline, not a language model";
const SCOPE = "This measures the SYSTEM: the search that builds plans, the permission gate, the executor and the independent verifier. It does not measure a language model: the planner is the deterministic planner and no model is called. The companies are synthetic copies of one demo business with generated crises, and every counterparty is a simulator with a fixed personality.";

const grp = (n: bigint) => n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ",");
export const gbp = (minor: string | bigint | null) => {
  if (minor === null) return "n/a";
  const v = BigInt(minor);
  const a = v < 0n ? -v : v;
  return `${v < 0n ? "-" : ""}GBP ${grp(a / 100n)}.${(a % 100n).toString().padStart(2, "0")}`;
};
const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((n * 100) / d).toFixed(1)}%`);
const frac = (n: number, d: number) => `${n}/${d} (${pct(n, d)})`;
const mean = (xs: bigint[]) => (xs.length === 0 ? null : xs.reduce((a, b) => a + b, 0n) / BigInt(xs.length));

export interface EvalRun {
  results: CaseResult[];
  seed: number;
  invariants: { name: string; value: number | boolean; ok: boolean }[];
  json: string;
  md: string;
  footprint: { clones: number; logRecords: number };
}

export interface SupplierGroup { key: string; label: string }
export const supplierGroup = (p: CaseParams): string => {
  const defers = p.shock !== "supplier_refusal" && p.supplierDefers;
  const cuts = p.shock !== "supplier_refusal" && p.supplierMinDepositPct < 30;
  return defers && cuts ? "defers and cuts the deposit" : defers ? "defers only" : cuts ? "cuts the deposit only" : "refuses both";
};
const SUPPLIER_ORDER = ["defers and cuts the deposit", "defers only", "cuts the deposit only", "refuses both"];

export async function runEval(opts: { cases: number; seed: number; log?: (s: string) => void }): Promise<EvalRun> {
  const log = opts.log ?? (() => undefined);
  const env = await createEnv();
  const params = generateCases(opts.cases, opts.seed);
  const results: CaseResult[] = [];
  let chainOk = true;
  const footprint = { clones: 0, logRecords: 0 };
  try {
    const { getEvidence } = await import("../../src/actions");
    for (const p of params) {
      const t0 = Date.now();
      const r = await runCase(env, p);
      results.push(r);
      footprint.clones++;
      const [c] = await env.owner`select count(*)::int n from action_records where business_id = ${r.businessId}`;
      footprint.logRecords += Number(c.n);
      const ev = (await getEvidence(env.db, r.businessId)) as { chain: { ok: boolean } };
      if (!ev.chain.ok) chainOk = false;
      log(`  case ${String(p.index).padStart(3)}  ${r.outcome.padEnd(24)} rounds ${r.rounds}  ${r.planType ?? "-"}  (${((Date.now() - t0) / 1000).toFixed(1)}s)${r.error ? `  ERROR ${r.error.slice(0, 700)}` : ""}`);
    }
  } finally {
    await closeEnv(env);
  }
  return { results, seed: opts.seed, footprint, ...build(results, params, opts.seed, chainOk) };
}

function build(results: CaseResult[], params: CaseParams[], seed: number, chainOk: boolean) {
  const n = results.length;
  const short = results.filter((r) => r.shortage);
  const count = (o: OutcomeClass) => results.filter((r) => r.outcome === o).length;
  const executed = short.filter((r) => r.rounds > 0);
  const verified = results.filter((r) => r.outcome === "resolved_verified" || r.outcome === "verified_gap_remains");
  const resolved = count("resolved_verified");
  const meanRounds = executed.length === 0 ? null : executed.reduce((a, r) => a + r.rounds, 0) / executed.length;
  const costs = verified.map((r) => BigInt(r.strategyCostMinor ?? "0"));
  const borrowing = verified.filter((r) => BigInt(r.borrowedMinor) > 0n).length;
  const gateDenials = results.reduce((a, r) => a + r.gateDenials, 0);
  const refusals = results.reduce((a, r) => a + r.counterpartyRefusals, 0);
  const limitViolations = results.reduce((a, r) => a + r.limitViolations.length, 0);
  const floorBreaches = results.reduce((a, r) => a + r.floorBreaches.length, 0);
  const unsigned = results.reduce((a, r) => a + r.unsignedExecutions, 0);
  const differs = results.filter((r) => r.verifiedButDiffers).length;
  const promiseDiffers = verified.filter((r) => r.promiseDiffers).length;
  const withError = results.filter((r) => r.error !== null);

  const invariants = [
    { name: "limit violations (payments or terms beyond a signed limit)", value: limitViolations, ok: limitViolations === 0 },
    { name: "floor breaches caused by the agent's scheduled items", value: floorBreaches, ok: floorBreaches === 0 },
    { name: "executions without a signed authorisation", value: unsigned, ok: unsigned === 0 },
    { name: "verified \"passed\" but independent recomputation differs", value: differs, ok: differs === 0 },
    { name: "action log chain verifies for every case", value: chainOk, ok: chainOk },
  ];

  // Baselines on the shortage cases.
  const base = (pick: (r: CaseResult) => { keepsCushion: boolean; aboveZero: boolean }) => ({ cushion: short.filter((r) => r.baselines && pick(r).keepsCushion).length, zero: short.filter((r) => r.baselines && pick(r).aboveZero).length });
  const bl = {
    nothing: base((r) => r.baselines!.nothing), financeAll: base((r) => r.baselines!.financeAll), bestSingle: base((r) => r.baselines!.bestSingle), agent: base((r) => r.baselines!.agent),
  };

  // Breakdowns.
  const byCap = [5, 10, 20, 30].map((cap) => {
    const rs = short.filter((r) => r.params.buyerDepositCapPct === cap);
    return { cap, shortage: rs.length, executedVerified: rs.filter((r) => r.outcome === "resolved_verified" || r.outcome === "verified_gap_remains").length, resolved: rs.filter((r) => r.outcome === "resolved_verified").length };
  });
  const bySupplier = SUPPLIER_ORDER.map((key) => {
    const rs = short.filter((r) => supplierGroup(r.params) === key);
    return { key, shortage: rs.length, executedVerified: rs.filter((r) => r.outcome === "resolved_verified" || r.outcome === "verified_gap_remains").length, resolved: rs.filter((r) => r.outcome === "resolved_verified").length };
  });

  // Cases where nothing inside the signed limits closes the gap.
  const noClose = short.filter((r) => r.closesWithinLimits === false);
  const reasonCounts = new Map<string, number>();
  for (const r of noClose) for (const why of r.noClosureReasons) reasonCounts.set(why, (reasonCounts.get(why) ?? 0) + 1);
  const reasons = [...reasonCounts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));

  // Reasons for unresolved shortage cases that the engine thought could be closed (systematic causes).
  const unresolvedClosable = short.filter((r) => r.closesWithinLimits === true && r.outcome !== "resolved_verified");
  const causeCounts = new Map<string, number>();
  for (const r of unresolvedClosable) causeCounts.set(r.outcome, (causeCounts.get(r.outcome) ?? 0) + 1);

  const summary = {
    cases: n,
    shortageCases: short.length,
    outcomes: Object.fromEntries(OUTCOMES.map((o) => [o, count(o)])),
    executedAndVerified: verified.length,
    resolvedVerified: resolved,
    meanRounds: meanRounds === null ? null : Number(meanRounds.toFixed(2)),
    meanStrategyCostMinor: mean(costs)?.toString() ?? null,
    verifiedNeedingBorrowing: borrowing,
    gateDenials, counterpartyRefusals: refusals, limitViolations, floorBreaches, executionsWithoutSignature: unsigned,
    verifiedButRecomputationDiffers: differs, verifiedPromiseDiffersFromAgreed: promiseDiffers, casesWithError: withError.length,
    chainVerifies: chainOk,
  };

  const strip = (r: CaseResult) => { const { businessId: _b, ...rest } = r; void _b; return rest; };
  const jsonObj = {
    note: HEADER,
    scope: SCOPE,
    seed, cases: n, asOf: "2026-10-15",
    ranges: RANGES,
    summary,
    baselines: {
      note: "Engine only, nothing executed, on the shortage cases. The first three assume every counterparty agrees and the lender charges its real fee; the agent row is what was actually agreed with the simulated counterparties and recomputed from the sandbox.",
      shortageCases: short.length,
      doNothing: bl.nothing, financeEverything: bl.financeAll, bestSingleAction: bl.bestSingle, agentExecuted: bl.agent,
    },
    byBuyerDepositCap: byCap,
    bySupplierBehaviour: bySupplier,
    noClosureWithinLimits: { cases: noClose.map((r) => r.index), reasons: Object.fromEntries(reasons) },
    closableButUnresolved: Object.fromEntries([...causeCounts.entries()].sort()),
    invariants,
    results: results.map(strip),
  };
  const json = JSON.stringify(jsonObj, (_k, v) => (typeof v === "bigint" ? v.toString() : v), 2) + "\n";

  // ---------------- Markdown ----------------
  const md: string[] = [HEADER, "", "# Evaluation on generated crises", "", `_Generated by \`bun run eval\`. Do not edit by hand. Seed ${seed}, ${n} generated companies, world date 2026-10-15._`, "", SCOPE, ""];
  md.push("## Setup", "", `- Seed ${seed}; ${n} cases; each case is a fresh throwaway copy of the demo business flagged as a test business. The generator (\`scripts/eval/generate.ts\`) uses a seeded mulberry32 stream per case: no Math.random, no clock.`,
    "- The ranges below were fixed before the first run and are not tuned to improve any rate.",
    "- Each case: perturb the copy, confirm the sample order (this runs the shortage check), plan with the deterministic planner, take the top-ranked plan that can run, sign it (owner and second approver, dev keys), execute it against the simulated counterparties, re-plan with the product's own limit of 2 rounds if a counterparty pushes back, then verify independently.",
    "- Limit violations and floor breaches are recomputed from the sandbox tables and the stored mandate, not taken from the engine's promise.", "",
    "| Parameter | Range |", "|---|---|", ...Object.entries(RANGES).map(([k, v]) => `| ${k} | ${v} |`), "");

  md.push("## Headline", "", "| Measure | Result |", "|---|---|",
    `| Generated cases | ${n} |`,
    `| Cases with a projected shortage | ${frac(short.length, n)} |`,
    ...OUTCOMES.map((o) => `| Outcome \`${o}\` | ${count(o)} (${pct(count(o), n)} of all cases${o === "no_shortage" ? "" : `, ${pct(count(o), short.length)} of shortage cases`}) |`),
    `| Executed and verified (passed the independent check) | ${frac(verified.length, short.length)} of shortage cases |`,
    `| Resolved and verified (lowest balance kept at or above the cushion) | ${frac(resolved, short.length)} of shortage cases |`,
    `| Mean rounds used (executed plans, per case that executed any) | ${meanRounds === null ? "n/a" : meanRounds.toFixed(2)} |`,
    `| Mean strategy cost (executed and verified cases) | ${gbp(mean(costs)?.toString() ?? null)} |`,
    `| Executed and verified cases that needed borrowing | ${frac(borrowing, verified.length)} |`,
    `| Gate denials (all cases) | ${gateDenials} |`,
    `| Counterparty refusals or out-of-terms counters (all cases) | ${refusals} |`,
    `| Limit violations | ${limitViolations} |`,
    `| Floor breaches caused by the agent | ${floorBreaches} |`,
    `| Verified "passed" but independent recomputation differs | ${differs} |`,
    `| Verified, agreed terms differ from the plan's promise (informational) | ${promiseDiffers} |`,
    `| Cases that recorded an error | ${withError.length} |`, "");

  md.push("## Baselines", "", `On the ${short.length} shortage cases. Do nothing, finance everything and best single action are computed by the engine only and assume every counterparty agrees, so they are favourable to the baselines. The agent row is what was actually agreed with the simulated counterparties.`, "",
    "| Approach | Lowest balance stays at or above the cushion | Lowest balance stays at or above zero |", "|---|---|---|",
    `| Do nothing | ${frac(bl.nothing.cushion, short.length)} | ${frac(bl.nothing.zero, short.length)} |`,
    `| Finance everything (maximum permitted invoice-finance advance only) | ${frac(bl.financeAll.cushion, short.length)} | ${frac(bl.financeAll.zero, short.length)} |`,
    `| Best single action | ${frac(bl.bestSingle.cushion, short.length)} | ${frac(bl.bestSingle.zero, short.length)} |`,
    `| The agent (executed, recomputed from the sandbox) | ${frac(bl.agent.cushion, short.length)} | ${frac(bl.agent.zero, short.length)} |`, "");

  md.push("## By buyer deposit cap", "", "| Largest deposit the buyer accepts | Shortage cases | Executed and verified | Resolved and verified |", "|---|---|---|---|",
    ...byCap.map((c) => `| ${c.cap}% | ${c.shortage} | ${c.executedVerified} | ${c.resolved} |`), "");
  md.push("## By supplier behaviour", "", "| Supplier | Shortage cases | Executed and verified | Resolved and verified |", "|---|---|---|---|",
    ...bySupplier.map((c) => `| ${c.key} | ${c.shortage} | ${c.executedVerified} | ${c.resolved} |`), "");

  md.push("## Cases where nothing inside the signed limits closes the gap", "",
    `${noClose.length} of ${short.length} shortage cases. Judged by the engine's search over every permitted action, assuming every counterparty agrees. Cases: ${noClose.length === 0 ? "none" : noClose.map((r) => r.index).join(", ")}.`, "",
    ...(reasons.length === 0 ? ["No such case."] : ["| Reason | Cases |", "|---|---|", ...reasons.map(([why, c]) => `| ${why.replaceAll("|", "/")} | ${c} |`)]), "");
  if (causeCounts.size > 0) md.push("### Shortage cases the engine could close but the run did not resolve", "", "| Outcome | Cases |", "|---|---|", ...[...causeCounts.entries()].sort().map(([o, c]) => `| ${o} | ${c} |`), "");

  md.push("## Invariants", "", "| Invariant | Value | Holds |", "|---|---|---|", ...invariants.map((i) => `| ${i.name} | ${typeof i.value === "boolean" ? (i.value ? "yes" : "no") : i.value} | ${i.ok ? "yes" : "NO"} |`), "");
  if (withError.length > 0) md.push("## Errors recorded", "", ...withError.map((r) => `- case ${r.index}: ${r.outcome}: ${r.error!.replaceAll(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi, "<id>")}`), "");
  md.push("## Every case", "", "| # | Parameters | Lowest before | Plan | Outcome | Rounds | Cost | Borrowed | Promised | Verified | Recomputed | Denials | Refusals |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...results.map((r) => `| ${r.index} | ${describeParams(r.params)} | ${gbp(r.lowestBeforeMinor)} | ${r.planType ?? "-"} | ${r.outcome} | ${r.rounds} | ${gbp(r.strategyCostMinor)} | ${gbp(BigInt(r.borrowedMinor) > 0n ? r.borrowedMinor : null)} | ${gbp(r.lowestPromisedMinor)} | ${gbp(r.lowestVerifiedMinor)} | ${gbp(r.lowestRecomputedMinor)} | ${r.gateDenials} | ${r.counterpartyRefusals} |`), "");
  md.push(
    "## Before the fix",
    "",
    "- First recorded run (same seed and ranges, kept in `fixtures/eval-results-before-fix.json`): 6 of 60 resolved and verified (10%), 11 verified with a gap, 19 rolled back, 24 stopped.",
    "- Causes: a lender fee above the plan's 2% assumption (24 stopped because the failed finance application stayed open and blocked the re-plan; 18 rolled back because a fee above the signed 3% limit had no way forward).",
    "- Fixed in the executor only: a failed or out-of-terms finance branch now withdraws its own open application, and a fee above the signed limit is a lender refusal (lever excluded, re-plan runs). The gate, signed terms, tolerances and limits were not changed.",
    "- The generator, seed and ranges were not changed; this file is the run after the fix.",
    "",
  );
  md.push("_Money is shown in pounds; the JSON file holds integer minor units. Reproduce with `bun run eval`._", "");
  return { invariants, json, md: md.join("\n") };
}
